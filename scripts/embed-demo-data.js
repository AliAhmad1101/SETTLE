// Embeds the deterministic demo dataset into the frontend so SETTLE also works
// as a fully standalone page when the backend server is not running.
// Run with: node scripts/embed-demo-data.js
const fs = require("fs");
const path = require("path");
const demo = require("../backend/demo");

const { orders, payments } = demo.buildDemo();
const json = JSON.stringify({ orders, payments }, null, 1);

const out = `// Embedded demo dataset, generated by scripts/embed-demo-data.js.
// Used by the standalone mode when the backend server is unreachable.
// Re run: node scripts/embed-demo-data.js
window.SETTLE_DEMO = ${json};
`;

const dir = path.join(__dirname, "..", "frontend", "js");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "demo-data.js"), out);
console.log(`Embedded ${orders.length} orders and ${payments.length} payments into frontend/js/demo-data.js`);